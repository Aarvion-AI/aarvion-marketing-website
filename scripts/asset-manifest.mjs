import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PRIORITY = ["webp", "avif", "png", "jpg", "jpeg", "svg"];

function scan(dir) {
  const abs = join(root, "public", dir);
  if (!existsSync(abs)) return {};
  const out = {};
  for (const file of readdirSync(abs).sort()) {
    const match = /^(.+)\.([a-z0-9]+)$/i.exec(file);
    if (!match) continue;
    const [, id, ext] = match;
    const rank = PRIORITY.indexOf(ext.toLowerCase());
    if (rank === -1) continue;
    const current = out[id];
    if (!current || rank < current.rank) out[id] = { rank, path: `/${dir}/${file}` };
  }
  return Object.fromEntries(Object.entries(out).map(([id, v]) => [id, v.path]));
}

const images = scan("images");
const logos = scan("logos");

const source = `// Generated by scripts/asset-manifest.mjs — do not edit.
export const IMAGES: Record<string, string> = ${JSON.stringify(images, null, 2)};
export const LOGOS: Record<string, string> = ${JSON.stringify(logos, null, 2)};
`;

mkdirSync(join(root, "lib"), { recursive: true });
writeFileSync(join(root, "lib", "asset-manifest.generated.ts"), source);
console.log(
  `[asset-manifest] ${Object.keys(images).length} images, ${Object.keys(logos).length} logos`,
);
